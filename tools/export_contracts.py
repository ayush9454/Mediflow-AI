#!/usr/bin/env python3
"""Export Pydantic contracts to deterministic OpenAPI/JSON Schema/Dart artifacts."""

import argparse
import inspect
import json
import re
from enum import Enum
from pathlib import Path

from pydantic import BaseModel, TypeAdapter

from mediflow import contracts
from mediflow.main import create_app

ROOT = Path(__file__).resolve().parents[1]


def json_text(value):
    return json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def dart_name(value):
    return re.sub(r"_([a-z])", lambda match: match.group(1).upper(), value)


def dart_literal(value):
    return json.dumps(value, ensure_ascii=False).replace("$", r"\$")


def unwrap(schema):
    if "anyOf" in schema:
        choices = [item for item in schema["anyOf"] if item.get("type") != "null"]
        if len(choices) != 1:
            raise ValueError("Use an explicit tagged contract rather than an ambiguous union.")
        return choices[0], True
    return schema, False


def dart_type(schema):
    schema, nullable = unwrap(schema)
    if "$ref" in schema:
        result = schema["$ref"].split("/")[-1]
    elif schema.get("format") == "date-time":
        result = "DateTime"
    elif schema.get("type") == "array":
        result = "List<" + dart_type(schema["items"]) + ">"
    else:
        result = {"string": "String", "integer": "int", "number": "double", "boolean": "bool"}[
            schema["type"]
        ]
    return result + ("?" if nullable else "")


def decode(schema, value):
    schema, nullable = unwrap(schema)
    if nullable:
        return value + " == null ? null : " + decode(schema, value)
    if "$ref" in schema:
        name = schema["$ref"].split("/")[-1]
        argument = (
            value + " as String"
            if name in ENUMS
            else "(" + value + " as Map).cast<String, Object?>()"
        )
        return name + ".fromJson(" + argument + ")"
    if schema.get("format") == "date-time":
        return "DateTime.parse(" + value + " as String)"
    if schema.get("type") == "array":
        return (
            "List<"
            + dart_type(schema["items"])
            + ">.unmodifiable(("
            + value
            + " as List).map((item) => "
            + decode(schema["items"], "item")
            + "))"
        )
    if schema.get("type") == "number":
        return "(" + value + " as num).toDouble()"
    return value + " as " + dart_type(schema)


def encode(schema, value):
    schema, nullable = unwrap(schema)
    if nullable:
        if "$ref" in schema:
            return value + "?.toJson()"
        if schema.get("format") == "date-time":
            return value + "?.toUtc().toIso8601String()"
        if schema.get("type") == "array":
            return value + "?.map((item) => " + encode(schema["items"], "item") + ").toList()"
        return value
    if "$ref" in schema:
        return value + ".toJson()"
    if schema.get("format") == "date-time":
        return value + ".toUtc().toIso8601String()"
    if schema.get("type") == "array":
        return value + ".map((item) => " + encode(schema["items"], "item") + ").toList()"
    return value


def dart_models(definitions):
    lines = [
        "// GENERATED by tools/export_contracts.py. Do not edit by hand.",
        "// The backend validates semantic constraints; these are typed wire models.",
        "// dart format off",
        "",
    ]
    for name in sorted(definitions):
        schema = definitions[name]
        if name in ENUMS:
            lines.append("enum " + name + " {")
            lines.extend(
                "  " + dart_name(item) + "(" + dart_literal(item) + ")," for item in schema["enum"]
            )
            lines[-1] = lines[-1][:-1] + ";"
            lines.extend(
                [
                    "",
                    "  const " + name + "(this.value);",
                    "  final String value;",
                    "  String toJson() => value;",
                    "  static " + name + " fromJson(String value) => values.firstWhere(",
                    "    (item) => item.value == value,",
                    "    orElse: () => throw const FormatException('Unknown " + name + " value'),",
                    "  );",
                    "}",
                    "",
                ]
            )
            continue
        properties = schema["properties"]
        lines.append("final class " + name + " {")
        lines.append("  const " + name + "({")
        lines.extend("    required this." + field + "," for field in properties)
        lines.append("  });")
        lines.append("")
        lines.extend(
            "  final " + dart_type(prop) + " " + field + ";" for field, prop in properties.items()
        )
        lines.append("")
        lines.append("  factory " + name + ".fromJson(Map<String, Object?> json) => " + name + "(")
        for field, prop in properties.items():
            value = "json[" + dart_literal(field) + "]"
            if "default" in prop and prop["default"] is not None:
                value = "(" + value + " ?? " + dart_literal(prop["default"]) + ")"
            lines.append("    " + field + ": " + decode(prop, value) + ",")
        lines.append("  );")
        lines.append("")
        lines.append("  Map<String, Object?> toJson() => {")
        lines.extend(
            "    " + dart_literal(field) + ": " + encode(prop, field) + ","
            for field, prop in properties.items()
        )
        lines.extend(["  };", "}", ""])
    return "\n".join(lines)


