def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail if generated contracts are stale"
    )
    args = parser.parse_args()
    definitions = {}
    for name, cls in inspect.getmembers(contracts, inspect.isclass):
        if cls.__module__ == contracts.__name__ and issubclass(cls, Enum):
            definitions[name] = TypeAdapter(cls).json_schema()
        if (
            cls.__module__ == contracts.__name__
            and issubclass(cls, BaseModel)
            and name not in {"WireModel", "VersionedModel"}
        ):
            schema = cls.model_json_schema(by_alias=True)
            definitions.update(schema.pop("$defs", {}))
            definitions[name] = schema
    global ENUMS
    ENUMS = {name for name, schema in definitions.items() if "enum" in schema}
    artifacts = {
        ROOT / "contracts" / "openapi.json": json_text(create_app().openapi()),
        ROOT / "contracts" / "models.schema.json": json_text(
            {
                "$schema": "https://json-schema.org/draft/2020-12/schema",
                "$defs": definitions,
            }
        ),
        ROOT / "app" / "lib" / "core" / "contracts" / "contracts.g.dart": dart_models(definitions),
    }
    for name, model in example_documents().items():
        artifacts[ROOT / "contracts" / "examples" / (name + ".json")] = json_text(
            model.model_dump(mode="json", by_alias=True)
        )
    changed = []
    for path, expected in artifacts.items():
        if not path.exists() or path.read_text() != expected:
            changed.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected)
    if args.check and changed:
        parser.exit(1, "Stale generated contracts: " + ", ".join(changed) + "\n")
    print(
        ("Checked" if args.check else "Exported")
        + " "
        + str(len(artifacts))
        + " contract artifacts."
    )


if __name__ == "__main__":
    main()
